// Generates src/config/abis.generated.ts from the Foundry artifacts in contracts/out.
// Run after `forge build`:  bun run gen:abis
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
// FluxoraPaymentsStandalone is the one payments contract. The app imports it as `fluxoraPaymentsAbi`; the
// longer name stays exported for scripts that were written against it.
const names = ['FluxoraToken', 'FluxoraPaymentsStandalone'] as const

let out = '// GENERATED by scripts/gen-abis.ts from contracts/out. Do not edit by hand.\n\n'
for (const name of names) {
  const artifact = JSON.parse(readFileSync(join(root, 'contracts', 'out', `${name}.sol`, `${name}.json`), 'utf8')) as {
    abi: unknown[]
  }
  const varName = name === 'FluxoraPaymentsStandalone' ? 'fluxoraPaymentsAbi' : name.charAt(0).toLowerCase() + name.slice(1) + 'Abi'
  out += `export const ${varName} = ${JSON.stringify(artifact.abi, null, 2)} as const\n\n`
  if (name === 'FluxoraPaymentsStandalone') out += 'export const fluxoraPaymentsStandaloneAbi = fluxoraPaymentsAbi\n\n'
}
writeFileSync(join(root, 'src', 'config', 'abis.generated.ts'), out)
console.log('wrote src/config/abis.generated.ts')
